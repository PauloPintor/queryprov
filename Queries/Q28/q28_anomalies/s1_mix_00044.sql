      where ss_quantity between 6 and 10
        and (ss_list_price between 38 and 38+10
          or ss_coupon_amt between 12171 and 12171+1000
          or ss_wholesale_cost between 17 and 17+20)) B2,
     (select avg(ss_list_price) B3_LP
            ,count(ss_list_price) B3_CNT
            ,count(distinct ss_list_price) B3_CNTD
            ,array_agg(store_sales.prov) prov
      from store_sales
      where ss_quantity between 11 and 15
        and (ss_list_price between 61 and 61+10
          or ss_coupon_amt between 13160 and 13160+1000
          or ss_wholesale_cost between 58 and 58+20)) B3,
